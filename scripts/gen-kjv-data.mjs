// Regenerates src/kjv-data.js from the `kjv` npm package (1769 KJV text,
// public domain). Run `npm run gen:kjv` after upgrading the `kjv` package;
// nothing else should need this — the output is a build input like
// index.html itself, not something to hand-edit.
//
// The 66-book canon and every verse's markup-stripped text get packed into
// one gzip'd, base64'd blob so "Add any verse by reference" has the whole
// KJV on hand without a network request. Raw verse JSON is ~4.8 MB; gzipped
// it's ~1.4 MB, comfortably inside the 16 MB artifact budget once inlined.
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ROOT = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(ROOT, "..", "src", "kjv-data.js");

const CANON = require("kjv/json/verses-1769.json");

// Same two editorial conventions test/verify-kjv.mjs strips: [word] marks
// translator-supplied words (italicised in print), # marks a paragraph
// start (the pilcrow). Markup, not wording — dropped so lookups return text
// in the same form the starter deck already uses.
const stripMarkup = s => s.replace(/^#\s*/, "").replace(/[[\]]/g, "").replace(/\s+/g, " ").trim();

const books = [];
const seen = new Set();
const data = {};

for (const [key, text] of Object.entries(CANON)) {
  const m = key.match(/^(.+) (\d+):(\d+)$/);
  if (!m) throw new Error("Unrecognized verse key: " + key);
  const book = m[1];
  if (!seen.has(book)) { seen.add(book); books.push(book); }
  data[key] = stripMarkup(text);
}

const gz = zlib.gzipSync(Buffer.from(JSON.stringify(data), "utf8"), { level: 9 });
const b64 = gz.toString("base64");

const out = `// Generated by \`npm run gen:kjv\` from the kjv npm package (1769 KJV,
// public domain — see scripts/gen-kjv-data.mjs). Do not hand-edit; a change
// here should come from re-running that script, not a manual patch.
const KJV_BOOKS = ${JSON.stringify(books)};
const KJV_DATA_GZ_B64 = "${b64}";
`;

fs.writeFileSync(OUT, out);
console.log(`Wrote ${OUT} (${books.length} books, ${Object.keys(data).length} verses, ${(gz.length / 1024).toFixed(0)} KB gzipped, ${(out.length / 1024).toFixed(0)} KB as written).`);
